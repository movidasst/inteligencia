const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const app=fs.readFileSync('app-v4.js','utf8');
const xp=fs.readFileSync('xp.js','utf8');
new vm.Script(app,{filename:'app-v4.js'});
new vm.Script(xp,{filename:'xp.js'});
assert.match(html,/data-view="xp"/);
assert.match(html,/id="view-xp"/);
assert.match(html,/id="importGroupName"/);
assert.match(html,/<script src="app-v4\.js"><\/script>[\s\S]*<script src="xp\.js"><\/script>/);
const ids=[...new Set([...xp.matchAll(/E\('([^']+)'\)/g)].map(x=>x[1]))];
for(const id of ids)assert.ok(html.includes('id="'+id+'"'),'Falta id: '+id);
assert.match(html,/id="xpGrantBtn"[^>]*disabled/);
assert.match(app,/admin_inteligencia_grupo_asignar/);
assert.match(app,/window\.openXpForImport\(currentImportId\)/);
assert.match(xp,/admin_inteligencia_xp_previsualizar/);
assert.match(xp,/admin_inteligencia_xp_confirmar/);
assert.match(xp,/p_asignaciones/);
assert.match(xp,/crypto\.randomUUID/);
assert.doesNotMatch(xp,/admin_calidad_|admin_whatsapp_xp_|admin_estudios_listar/);
console.log('Group XP smoke tests passed:',ids.length,'elements.');
